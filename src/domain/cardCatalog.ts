// Card-art catalog, read from the bundled cards/card-art/manifest.json.
// Pure: parsing, grouping into institutions, naming, colour maths.
//
// manifest.json entries look like:
//   { "id": "td/aeroplan", "label": "TD Aeroplane", "bank": "td",
//     "file": "td/aeroplan.jpeg", "group": [note, region, ...sections] }

export type CardNetwork = 'visa' | 'mastercard' | 'amex' | 'interac' | 'discover' | 'unionpay' | 'other';

export interface CatalogCard {
  id: string;
  name: string; // as labelled in the manifest
  institutionId: string; // the bank folder, e.g. "td"
  network: CardNetwork;
  kind: 'credit' | 'debit';
  region?: string; // continent, e.g. "North America"
  file: string; // path inside card-art/
  cover?: PrintedCover; // the art has a sample name/number printed on it
}

/**
 * How a printed sample name/number is hidden (from card-art/clean/index.json,
 * generated by scripts/clean-card-art.py): a cleaned copy of the image, or a
 * small label drawn over the original. box = [x0, y0, x1, y1] as card fractions.
 */
export type PrintedCover = { method: 'clean'; file: string; box: Box } | { method: 'label'; box: Box; color?: string };
export type Box = [number, number, number, number];

export interface Institution {
  id: string; // bank folder, or "custom/<slug>" for ones the user created
  name: string;
  color?: string; // custom institutions carry their own; bundled ones get it from their art
  custom?: boolean;
}

const str = (v: unknown): string | undefined => (typeof v === 'string' && v.trim() ? v.trim() : undefined);

export function networkFrom(label: string, institutionId: string): CardNetwork {
  const s = `${label} ${institutionId}`.toLowerCase();
  if (/\bamex\b|american[- ]express/.test(s)) return 'amex';
  if (/master ?card|world elite|\bmc\b/.test(s)) return 'mastercard';
  if (/\bvisa\b|\bvi\b|infinite/.test(s)) return 'visa';
  if (/discover/.test(s)) return 'discover';
  if (/union ?pay|银联/.test(s)) return 'unionpay';
  if (/interac/.test(s)) return 'interac';
  return 'other';
}

export function kindFrom(label: string, group: readonly string[]): 'credit' | 'debit' {
  const s = `${label} ${group.join(' ')}`.toLowerCase();
  return /debit|借记|access card|client card|cash card/.test(s) && !/credit cards/.test(group.join(' ').toLowerCase()) ? 'debit' : 'credit';
}

/** Parse the manifest; malformed or duplicate entries are skipped. */
export function parseManifest(json: unknown): CatalogCard[] {
  if (!Array.isArray(json)) return [];
  const seen = new Set<string>();
  const out: CatalogCard[] = [];
  for (const raw of json as Record<string, unknown>[]) {
    const id = str(raw?.id);
    const file = str(raw?.file);
    const bank = str(raw?.bank);
    if (!id || !file || !bank || seen.has(id) || file.includes('..')) continue;
    seen.add(id);
    const label = str(raw.label) ?? id;
    const group = Array.isArray(raw.group) ? raw.group.filter((g): g is string => typeof g === 'string') : [];
    // group[0] is a curator's note in this dataset; group[1] is the country.
    const region = regionName(group[1]);
    out.push({ id, name: label, institutionId: bank, network: networkFrom(label, bank), kind: kindFrom(label, group), ...(region ? { region } : {}), file });
  }
  return out;
}

// ---------- continents ----------
// The picker groups by continent, not country: Canadian and US banks issue cards on
// both sides of the border (TD, BMO, Amex), so one country often hid the right card.

const CONTINENT: Record<string, string> = {
  'United States': 'North America', Canada: 'North America',
  'Greater China': 'Asia', Japan: 'Asia', Singapore: 'Asia',
  UK: 'Europe', 'EU?': 'Europe', Netherlands: 'Europe',
  Australia: 'Oceania',
};

const regionName = (raw: string | undefined): string | undefined => (raw ? (CONTINENT[raw] ?? raw) : undefined);

/** Continents that have card art, most cards first. */
export function continents(cards: readonly CatalogCard[]): string[] {
  const n = new Map<string, number>();
  for (const c of cards) if (c.region) n.set(c.region, (n.get(c.region) ?? 0) + 1);
  return [...n.keys()].sort((a, b) => n.get(b)! - n.get(a)! || a.localeCompare(b));
}

const CURRENCY_CONTINENT: Record<string, string> = {
  CAD: 'North America', USD: 'North America', MXN: 'North America',
  GBP: 'Europe', EUR: 'Europe', CHF: 'Europe', SEK: 'Europe', NOK: 'Europe', DKK: 'Europe',
  JPY: 'Asia', SGD: 'Asia', CNY: 'Asia', HKD: 'Asia', TWD: 'Asia', KRW: 'Asia', INR: 'Asia',
  AUD: 'Oceania', NZD: 'Oceania',
};

/** The continent to open the picker on: the one the current institution is from, else the home currency's. */
export function defaultContinent(cards: readonly CatalogCard[], currency: string, institutionId?: string): string | undefined {
  const all = continents(cards);
  const home = CURRENCY_CONTINENT[currency.toUpperCase()];
  if (institutionId) {
    const from = new Set(cards.filter((c) => c.institutionId === institutionId).map((c) => c.region));
    if (from.size) return home && from.has(home) ? home : all.find((r) => from.has(r));
  }
  return home && all.includes(home) ? home : undefined;
}

const ACRONYMS: Record<string, string> = {
  td: 'TD', rbc: 'RBC', bmo: 'BMO', cibc: 'CIBC', hsbc: 'HSBC', icbc: 'ICBC', anz: 'ANZ', ocbc: 'OCBC', pnc: 'PNC', fnbo: 'FNBO',
  ctbc: 'CTBC', za: 'ZA', us: 'U.S.', eq: 'EQ', pc: 'PC', jd: 'JD', n26: 'N26', aod: 'AOD', sofi: 'SoFi', ing: 'ING', mbna: 'MBNA',
  com: '.com', etrade: 'E*TRADE', hmbradley: 'HMBradley', paypal: 'PayPal', metamask: 'MetaMask', paypower: 'PayPower', tapngo: "Tap & Go",
  treecard: 'TreeCard', penfed: 'PenFed', securityplus: 'SecurityPlus',
};
const SMALL = new Set(['of', 'and', 'the']);

/** "bank-of-china-hong-kong" → "Bank of China Hong Kong", "td" → "TD", "crypto-com" → "Crypto.com". */
export function institutionName(slug: string): string {
  return slug
    .split('-')
    .map((w, i) => ACRONYMS[w] ?? (i > 0 && SMALL.has(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(' ')
    .replace(/ \.com$/, '.com');
}

/** Institutions that have art (in the continent `country`, when given), plus the user's own, sorted by name. */
export function institutions(cards: readonly CatalogCard[], custom: readonly Institution[] = [], country?: string): Institution[] {
  const ids = [...new Set(cards.filter((c) => !country || c.region === country).map((c) => c.institutionId))];
  const all: Institution[] = [...ids.map((id) => ({ id, name: institutionName(id) })), ...custom.map((c) => ({ ...c, custom: true }))];
  return all.sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }));
}

/** An institution's cards, limited to `country` when it has any there. */
export function cardsOf(cards: readonly CatalogCard[], institutionId: string, country?: string): CatalogCard[] {
  const all = cards.filter((c) => c.institutionId === institutionId).sort((a, b) => a.name.localeCompare(b.name));
  const local = country ? all.filter((c) => c.region === country) : [];
  return local.length ? local : all;
}

/** Card name without the institution repeated: "BMO Cashback" under BMO → "Cashback". */
export function shortCardName(card: Pick<CatalogCard, 'name' | 'institutionId'>): string {
  const inst = institutionName(card.institutionId).toLowerCase();
  const first = card.institutionId.split('-')[0]!.toLowerCase();
  for (const prefix of [inst, first]) {
    if (card.name.toLowerCase().startsWith(`${prefix} `)) {
      const rest = card.name.slice(prefix.length).trim();
      if (rest && !/^bank$/i.test(rest)) return rest;
    }
  }
  return card.name;
}

/**
 * Labels for an institution's card list: short names, with same-named cards told
 * apart by their file name ("TD Bank · Debit Us 2").
 */
export function cardLabels(cards: readonly CatalogCard[]): Map<string, string> {
  const base = new Map(cards.map((c) => [c.id, shortCardName(c)]));
  const counts = new Map<string, number>();
  for (const l of base.values()) counts.set(l, (counts.get(l) ?? 0) + 1);
  const humanise = (id: string) => (id.split('/').pop() ?? id).split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  return new Map(cards.map((c) => [c.id, (counts.get(base.get(c.id)!) ?? 0) > 1 ? `${base.get(c.id)} · ${humanise(c.id)}` : base.get(c.id)!]));
}

export const customInstitutionId = (name: string): string =>
  `custom/${name.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'bank'}`;

const isBox = (b: unknown): b is Box =>
  Array.isArray(b) && b.length === 4 && b.every((n) => typeof n === 'number' && n >= 0 && n <= 1) && b[0] < b[2] && b[1] < b[3];

/** Attach covers from clean/index.json. Malformed entries and unknown ids are ignored. */
export function applyCovers(cards: readonly CatalogCard[], index: unknown): CatalogCard[] {
  if (!index || typeof index !== 'object') return [...cards];
  const map = index as Record<string, { method?: unknown; file?: unknown; box?: unknown; color?: unknown }>;
  return cards.map((c) => {
    const e = map[c.id];
    if (!e || !isBox(e.box)) return c;
    if (e.method === 'clean' && typeof e.file === 'string' && !e.file.includes('..')) return { ...c, cover: { method: 'clean', file: e.file, box: e.box } };
    if (e.method === 'label') return { ...c, cover: { method: 'label', box: e.box, ...(isHexColor(e.color) ? { color: e.color } : {}) } };
    return c;
  });
}

/** Two letters for an institution badge: "Bank of America" → "BA", "TD" → "TD". */
export function institutionInitials(name: string): string {
  const words = name.split(/\s+/).filter((w) => w && !SMALL.has(w.toLowerCase()));
  if (words.length === 1) return words[0]!.slice(0, 3).toUpperCase();
  return words.slice(0, 2).map((w) => w[0]!.toUpperCase()).join('');
}

// ---------- colour ----------

export const isHexColor = (s: unknown): s is string => typeof s === 'string' && /^#[0-9a-f]{6}$/i.test(s);

const toHex = (r: number, g: number, b: number) => `#${[r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')}`;

/**
 * The brand colour of a card image: the most common colour bucket, preferring
 * saturated colours and ignoring near-white, near-black and transparent pixels
 * (text, logos, background). Falls back to the average when the art is greyscale.
 */
export function dominantColor(rgba: ArrayLike<number>): string {
  const buckets = new Map<number, { n: number; r: number; g: number; b: number; w: number }>();
  let ar = 0;
  let ag = 0;
  let ab = 0;
  let an = 0;
  for (let i = 0; i + 3 < rgba.length; i += 4) {
    const r = rgba[i]!;
    const g = rgba[i + 1]!;
    const b = rgba[i + 2]!;
    if (rgba[i + 3]! < 128) continue;
    ar += r;
    ag += g;
    ab += b;
    an++;
    const max = Math.max(r, g, b);
    const min = Math.min(r, g, b);
    const sat = max === 0 ? 0 : (max - min) / max;
    if (max > 240 && sat < 0.1) continue; // white
    if (max < 25) continue; // black
    const key = ((r >> 5) << 6) | ((g >> 5) << 3) | (b >> 5);
    const e = buckets.get(key) ?? { n: 0, r: 0, g: 0, b: 0, w: 0 };
    e.n++;
    e.r += r;
    e.g += g;
    e.b += b;
    e.w += 1 + sat * 2; // saturated colours count up to 3×
    buckets.set(key, e);
  }
  const best = [...buckets.values()].sort((x, y) => y.w - x.w)[0];
  if (best) return toHex(best.r / best.n, best.g / best.n, best.b / best.n);
  return an ? toHex(ar / an, ag / an, ab / an) : '#2b2b2b';
}

/** Relative luminance (WCAG). */
function luminance(hex: string): number {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!;
}

/** Text colour that reads on a card of this colour. */
export const textOn = (hex: string): string => (isHexColor(hex) && luminance(hex) > 0.42 ? '#111111' : '#ffffff');

